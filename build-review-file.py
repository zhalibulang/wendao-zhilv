    lines.append('> 修正版 r4：已扩充短答案、重写错位条目、补充考察要点。\n')
    lines.append(f'> 总考点数：{len(data)}\n')

    # 目录
    lines.append('## 目录\n')
    subj_order = [
        '科目一 政策与法律法规',
        '科目二 导游业务',
        '科目三 全国导游基础知识',
        '科目四 地方导游基础知识',
        '科目五 导游服务能力（现场考试）'
    ]
    for i, subj in enumerate(subj_order, 1):
        if subj in by_subject:
            items = by_subject[subj]
            lines.append(f'{i}. [{subj}](#{i}-{subj}) ({len(items)}条)')
    lines.append('')

    # 各科目内容
    for i, subj in enumerate(subj_order, 1):
        if subj not in by_subject:
            continue
        items = by_subject[subj]
        lines.append(f'\n---\n')
        lines.append(f'## {i}. {subj}\n')
        lines.append(f'共 {len(items)} 条考点\n')

        # 按module分组
        by_module = defaultdict(list)
        for d in items:
            by_module[d.get('module', '其他')].append(d)

        for mod, mod_items in sorted(by_module.items()):
            lines.append(f'\n### {mod} ({len(mod_items)}条)\n')
            for d in mod_items:
                lines.append(f'#### {d["id"]} {d.get("title", "")}\n')
                lines.append(f'**考察要点**：{d.get("exam_tip", "—")}\n')
                lines.append(f'**参考答案**：\n')
                lines.append(f'{d.get("text", "—")}\n')
                if d.get('anchor'):
                    lines.append(f'**记忆锚**：{d["anchor"]}\n')
                if d.get('origin'):
                    lines.append(f'**来源**：{d["origin"]}\n')
                lines.append('')

    md_content = '\n'.join(lines)
    with open(md_out, 'w', encoding='utf-8') as f:
        f.write(md_content)
    print(f'Markdown输出: {md_out}')

    # 统计
    print(f'\n=== 修正统计 ===')
    fix_a = sum(1 for d in data if d.get('version') == '2026-r4-修正' and d['id'] in ENRICH_S5_07)
    fix_b = sum(1 for d in data if d.get('version') == '2026-r4-修正' and d['id'] in REWRITE_MISPLACED)
    fix_c = sum(1 for d in data if d.get('version') == '2026-r4-修正' and d['id'] in ENRICH_SHORT_SCENIC)
    print(f'修正A(纯问答景点扩充): {fix_a}条')
    print(f'修正B(错位条目重写): {fix_b}条')
    print(f'修正C(短答案扩充): {fix_c}条')
    print(f'修正D(补充exam_tip): 全部586条')
    print(f'总输出: {len(data)}条')

